def check_supabase_connection() -> Tuple[bool, str]:
    """
    Supabase REST 엔드포인트 연결 상태 및 qc_data 테이블 존재 여부를 검사합니다.
    """
    try:
        response = requests.get(
            f"{REST_ENDPOINT}?select=id&limit=1",
            headers=HEADERS,
            timeout=3.5,
        )
        if response.status_code == 200:
            return True, "Supabase 클라우드 데이터베이스 정상 연동됨"
        elif response.status_code == 404:
            return False, "Supabase 연결 성공, 단 'qc_data' 테이블 미생성 상태 (로컬 캐시 모드 가동)"
        else:
            return False, f"Supabase 응답 코드: {response.status_code} ({response.text[:120]})"
    except Exception as e:
        return False, f"Supabase 통신 지연/오류: {str(e)[:100]}"


def insert_qc_data(
    temperature: float,
    humidity: float,
    dimension: float,
    spc_status: str,
    defect_prob: float,
    is_defect: int,
) -> Dict[str, Any]:
    """
    신규 공정 품질 데이터를 Supabase 클라우드 DB에 저장합니다.
    (테이블 미생성 또는 연결 실패 시 인메모리 캐시로 자동 폴백)
    """
    global _AUTO_ID_COUNTER
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    payload = {
        "temperature": round(float(temperature), 2),
        "humidity": round(float(humidity), 2),
        "dimension": round(float(dimension), 4),
        "spc_status": spc_status,
        "defect_prob": round(float(defect_prob), 2),
        "is_defect": int(is_defect),
    }

    try:
        response = requests.post(REST_ENDPOINT, headers=HEADERS, json=payload, timeout=4.0)
        if response.status_code in (200, 201):
            data = response.json()
            if isinstance(data, list) and len(data) > 0:
                record = data[0]
                logger.info(f"Supabase 저장 성공 (ID: {record.get('id')})")
                return record
            return payload
        else:
            logger.warning(f"Supabase POST 실패 ({response.status_code}): {response.text}")
    except Exception as e:
        logger.warning(f"Supabase POST 요청 중 예외 발생, 인메모리 캐시로 대체: {e}")

    # Fallback to In-Memory Cache
    fallback_record = {
        "id": _AUTO_ID_COUNTER,
        "timestamp": now_str,
        **payload,
    }
    _AUTO_ID_COUNTER += 1
    _IN_MEMORY_RECORDS.insert(0, fallback_record)
    return fallback_record


def fetch_all_qc_data(limit: int = 100) -> List[Dict[str, Any]]:
    """
    저장된 모든 품질 데이터를 최신순으로 조회합니다.
    """
    try:
        response = requests.get(
            f"{REST_ENDPOINT}?select=*&order=id.desc&limit={limit}",
            headers=HEADERS,
            timeout=4.0,
        )
        if response.status_code == 200:
            records = response.json()
            if isinstance(records, list):
                # 일시 포맷 정돈
                for r in records:
                    ts = r.get("timestamp", "")
                    if "T" in str(ts):
                        try:
                            # 2026-11-18T10:15:20.123456+00:00 -> 2026-11-18 10:15:20
                            dt = datetime.fromisoformat(ts.replace("Z", "+00:00"))
                            r["timestamp"] = dt.strftime("%Y-%m-%d %H:%M:%S")
                        except Exception:
                            pass
                return records
    except Exception as e:
        logger.warning(f"Supabase GET 요청 실패, 인메모리 캐시 반환: {e}")

    return _IN_MEMORY_RECORDS[:limit]


def fetch_dimension_history(limit: int = 100) -> List[float]:
    """
    SPC 관리선(CL/UCL/LCL) 산출을 위해 최근 치수(dimension) 측정값 목록을 조회합니다.
    (오래된 순 -> 최신순 정렬)
    """
    records = fetch_all_qc_data(limit=limit)
    # 최신순을 오래된 순으로 뒤집어서 반환
    dims = [float(r["dimension"]) for r in reversed(records) if "dimension" in r]
    return dims


def clear_all_qc_data() -> bool:
    """
    품질 측정 데이터를 전체 초기화합니다.
    """
    global _IN_MEMORY_RECORDS, _AUTO_ID_COUNTER
    _IN_MEMORY_RECORDS.clear()
    _AUTO_ID_COUNTER = 1

    try:
        response = requests.delete(
            f"{REST_ENDPOINT}?id=gt.0",
            headers=HEADERS,
            timeout=4.0,
        )
        if response.status_code in (200, 204):
            logger.info("Supabase 데이터 전체 삭제 완료")
            return True
    except Exception as e:
        logger.warning(f"Supabase DELETE 요청 실패: {e}")

    return True


